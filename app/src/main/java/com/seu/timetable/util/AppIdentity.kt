package com.seu.timetable.util

/**
 * 应用对外的名字。
 *
 * ★ 必须与 `res/values/strings.xml` 里的 `app_name`（即桌面图标下显示的那个名字）
 * **逐字一致**。
 *
 * 原因很实际：多处用户可见文案要引导用户去「系统设置 → 应用 → 这个名字」里找本应用
 * （开通知权限、开「创建桌面快捷方式」权限、在小部件列表里认出它）。
 * 名字一旦对不上，这些文案就从"帮助"变成了"误导"，而用户报障时通常只会说
 * "按你们说的找不到"。
 *
 * 之所以在这里另存一份、而不是在读文案处直接取字符串资源：
 * 这些文案由纯 Kotlin 对象生成（如 `WidgetGuidance`），会被 JVM 单测直接调用，
 * 那里没有 Context，取不到资源。两处必须同步修改，故此注释即为那条提醒。
 */
object AppIdentity {

    /** 与应用名一致，用于系统设置路径指引、小部件列表名称等。 */
    const val DISPLAY_NAME = "CHU课表(友友版)"

    /**
     * 下载到公共目录的更新包文件名。
     *
     * 刻意不含括号与空格：它要作为真实路径落到外部存储上，
     * 括号在部分文件管理器与分享面板里会被转义得很难看。
     */
    const val UPDATE_APK_NAME = "CHU课表-update.apk"
}
